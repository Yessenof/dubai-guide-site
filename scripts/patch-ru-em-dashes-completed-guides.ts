import Database from "better-sqlite3";
import path from "path";

const DB_PATH = path.resolve(process.cwd(), "data/guides.db");
const db = new Database(DB_PATH);

// ── Helpers ─────────────────────────────────────────────────────────────────

function countEmDashes(text: string): number {
  return (text.match(/—/g) || []).length;
}

function assertNoEmDash(label: string, text: string) {
  const n = countEmDashes(text);
  if (n > 0) throw new Error(`Em-dash found in ${label}: ${text.slice(0, 80)}`);
}

const guideUpdate = db.prepare(`
  UPDATE guides
  SET ru_title = ?, ru_summary = ?, ru_audience = ?, ru_overview = ?
  WHERE slug = ?
`);

const stepUpdate = db.prepare(`
  UPDATE steps
  SET ru_title = ?, ru_what = ?, ru_where = ?, ru_address = ?, ru_advice = ?, ru_warning = ?
  WHERE guide_id = (SELECT id FROM guides WHERE slug = ?) AND step_order = ?
`);

